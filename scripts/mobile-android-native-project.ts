import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

/**
 * Every repository path `expo prebuild --platform android` reads to generate `apps/mobile/android`: the app config and
 * the package manifest it imports, the local config plugins and their JSON, the icon and splash image, and the lockfile
 * that pins the Expo template and every autolinked native module. `mobile-android-native-project.test.ts` fails when
 * the config or a plugin starts importing a file outside this list.
 */
export const ANDROID_PREBUILD_INPUT_PATHS = [
    'apps/mobile/app.config.ts',
    'apps/mobile/package.json',
    'apps/mobile/plugins',
    'build/icon.png',
    'pnpm-lock.yaml',
] as const;

/**
 * Gradle state and outputs under `android/`; everything else there is generated by prebuild.
 */
const GENERATED_DIRECTORY_NAMES = new Set(['.cxx', '.gradle', '.kotlin', 'build']);

const STAMP_FILE = '.caxri-prebuild.json';

interface AndroidPrebuildStamp {
    inputs: string;
    project: string;
    schemaVersion: 1;
}

export type AndroidPrebuildDecision =
    | { action: 'regenerate'; reason: 'inputs-changed' | 'project-modified' | 'stamp-missing' }
    | { action: 'reuse' };

/**
 * Fingerprints the prebuild inputs from their Git object ids. The runner already requires a clean tree at the frozen
 * commit, so the committed objects are exactly the files prebuild reads.
 */
export function androidPrebuildInputFingerprint(readObjectId: (path: string) => string): string {
    const hash = createHash('sha256');
    for (const path of ANDROID_PREBUILD_INPUT_PATHS)
        hash.update(`${path}\0${readObjectId(path)}\n`);
    return hash.digest('hex');
}

async function listProjectFiles(directory: string): Promise<string[]> {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(
        entries.map(async (entry) => {
            const path = join(directory, entry.name);
            if (entry.isDirectory())
                return GENERATED_DIRECTORY_NAMES.has(entry.name) ? [] : listProjectFiles(path);
            return entry.name === STAMP_FILE ? [] : [path];
        }),
    );
    return nested.flat();
}

/**
 * Hashes the generated native sources, so a project edited or regenerated by another command after the stamp was
 * written is never mistaken for the one this runner generated.
 */
export async function hashAndroidNativeProject(androidDirectory: string): Promise<string> {
    const files = (await listProjectFiles(androidDirectory)).toSorted((left, right) =>
        left.localeCompare(right),
    );
    const contents = await Promise.all(files.map((file) => readFile(file)));
    const hash = createHash('sha256');
    for (const [index, file] of files.entries()) {
        hash.update(`${relative(androidDirectory, file)}\0`);
        hash.update(contents[index]);
        hash.update('\0');
    }
    return hash.digest('hex');
}

export function decideAndroidPrebuild(
    stamp: AndroidPrebuildStamp | undefined,
    current: { inputs: string; project: string | undefined },
): AndroidPrebuildDecision {
    if (!stamp || current.project === undefined)
        return { action: 'regenerate', reason: 'stamp-missing' };
    if (stamp.inputs !== current.inputs) return { action: 'regenerate', reason: 'inputs-changed' };
    if (stamp.project !== current.project)
        return { action: 'regenerate', reason: 'project-modified' };
    return { action: 'reuse' };
}

export async function readAndroidPrebuildStamp(
    androidDirectory: string,
): Promise<AndroidPrebuildStamp | undefined> {
    try {
        const value = JSON.parse(
            await readFile(join(androidDirectory, STAMP_FILE), 'utf8'),
        ) as Partial<AndroidPrebuildStamp>;
        return value.schemaVersion === 1 &&
            typeof value.inputs === 'string' &&
            typeof value.project === 'string'
            ? (value as AndroidPrebuildStamp)
            : undefined;
    } catch {
        return undefined;
    }
}

export async function writeAndroidPrebuildStamp(
    androidDirectory: string,
    inputs: string,
): Promise<void> {
    const stamp: AndroidPrebuildStamp = {
        inputs,
        project: await hashAndroidNativeProject(androidDirectory),
        schemaVersion: 1,
    };
    await writeFile(join(androidDirectory, STAMP_FILE), `${JSON.stringify(stamp, null, 4)}\n`);
}

/**
 * The ABI the release APK must contain for one emulator, read from `ro.product.cpu.abi`. Building only that ABI skips
 * compiling every native module for the three architectures the emulator never loads.
 */
export function parseAndroidEmulatorAbi(source: string): 'arm64-v8a' | 'x86_64' {
    const abi = source.trim();
    if (abi !== 'arm64-v8a' && abi !== 'x86_64')
        throw new Error('Android Acceptance supports only arm64-v8a or x86_64 emulators');
    return abi;
}
