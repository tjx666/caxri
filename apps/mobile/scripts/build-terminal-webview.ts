import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { draculaTheme } from '@caxri/protocol';
import { format, resolveConfig } from 'prettier';

const entry = fileURLToPath(new URL('terminal-webview-entry.ts', import.meta.url));
const stylesheet = fileURLToPath(
    new URL('../node_modules/@xterm/xterm/css/xterm.css', import.meta.url),
);
const destination = fileURLToPath(
    new URL('../src/features/terminal/terminal-webview.generated.ts', import.meta.url),
);

interface BunBuildOutput {
    path: string;
    text(): Promise<string>;
}

declare const Bun: {
    build(options: {
        entrypoints: string[];
        minify: boolean;
        target: 'browser';
    }): Promise<{ success: boolean; outputs: BunBuildOutput[] }>;
};

const result = await Bun.build({
    entrypoints: [entry],
    minify: true,
    target: 'browser',
});
if (!result.success) throw new Error('Unable to bundle the offline Terminal document');
const output = result.outputs.find((item) => item.path.endsWith('.js'));
if (!output) throw new Error('Terminal document has no JavaScript output');
const javascript = (await output.text()).replaceAll('</script', String.raw`<\/script`);
/**
 * The vendored CSS cites JSLinux over HTTP; use its verified public HTTPS URL in the tracked document.
 */
const css = (await readFile(stylesheet, 'utf8'))
    .replaceAll('</style', String.raw`<\/style`)
    .replace(/http:\/\/bellard\.org\/jslinux\//u, 'https://bellard.org/jslinux/');
const html = `<!doctype html>
<html><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; connect-src 'none'; img-src data:; script-src 'unsafe-inline'; style-src 'unsafe-inline'; font-src 'none'; media-src 'none'; frame-src 'none'; worker-src 'none'; object-src 'none'; form-action 'none'; base-uri 'none'">
<style>${css}\nhtml,body,#viewport{margin:0;width:100%;height:100%;overflow:hidden;background:${draculaTheme.terminal.background}}#viewport{overflow:auto;position:absolute;inset:0}#frame{position:relative}#stage{position:absolute;left:0;top:0;transform-origin:top left}.xterm{padding:0}</style>
</head><body><div id="viewport"><div id="frame"><div id="stage"></div></div></div>
<script>window.__CAXRI_TERMINAL_ID__=__TERMINAL_ID_JSON__;window.__CAXRI_TERMINAL_THEME__=${JSON.stringify(draculaTheme.terminal)};${javascript}</script>
</body></html>`;
const source = `/**\n * Generated by apps/mobile/scripts/build-terminal-webview.ts.\n */\nexport const terminalWebviewHtml = ${JSON.stringify(html)};\n`;
const options = (await resolveConfig(destination)) ?? {};
await writeFile(destination, await format(source, { ...options, filepath: destination }));
